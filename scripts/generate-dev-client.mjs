/**
 * Generate the Prisma client for LOCAL SQLite dev — without editing the
 * committed schema.
 *
 * Why this exists
 * ---------------
 * prisma/schema.prisma pins `provider = "postgresql"` because the deployed DB
 * is Neon Postgres and `prisma migrate deploy` must match migration_lock.toml.
 * Local dev, however, runs against `DATABASE_URL="file:./dev.db"` (see .env).
 *
 * Prisma validates the URL protocol against the provider baked into the
 * GENERATED client, so a client generated from the committed schema rejects a
 * `file:` URL with:
 *
 *     Error validating datasource `db`: the URL must start with the protocol
 *     `postgresql://` or `postgres://`
 *
 * A bare `npx prisma generate` (or anything that triggers it, e.g. a fresh
 * `npm install`) therefore breaks `npm run dev:web`. This script derives a
 * SQLite variant of the schema in-memory, generates from that, and leaves
 * prisma/schema.prisma untouched — so deploys are unaffected.
 *
 * The derived schema is rewritten from the committed one on every run, so it
 * can never drift from the real model definitions.
 *
 * Usage:  npm run db:generate:dev
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(root, "prisma", "schema.prisma");
// Must live in prisma/ — Prisma resolves a relative sqlite path (file:./dev.db)
// against the SCHEMA's directory, not the cwd. Gitignored.
const DERIVED = join(root, "prisma", "schema.dev-sqlite.prisma");

const schema = readFileSync(SOURCE, "utf8");

// Replace ONLY the datasource provider. Anchored to the datasource block so a
// generator's `provider = "prisma-client-js"` is never touched.
const datasource = /(datasource\s+\w+\s*\{[\s\S]*?provider\s*=\s*)"postgresql"/;
if (!datasource.test(schema)) {
  const already = /datasource\s+\w+\s*\{[\s\S]*?provider\s*=\s*"sqlite"/.test(schema);
  console.error(
    already
      ? "[dev-client] prisma/schema.prisma already says sqlite — run `npx prisma generate` directly."
      : "[dev-client] Could not find a postgresql datasource provider in prisma/schema.prisma. Aborting rather than generating a client that may not match your database.",
  );
  process.exit(1);
}

writeFileSync(
  DERIVED,
  "// GENERATED by scripts/generate-dev-client.mjs — do not edit, do not commit.\n" +
    "// Derived from prisma/schema.prisma with the datasource provider swapped to\n" +
    "// sqlite for local dev. Regenerated on every `npm run db:generate:dev`.\n" +
    schema.replace(datasource, '$1"sqlite"'),
  "utf8",
);

console.log("[dev-client] Generating Prisma client for SQLite (local dev)…");
// Run the Prisma CLI's JS entry with THIS node binary. Avoids `npx` entirely:
// Node 24 on Windows refuses to spawn a .cmd shim without shell:true, and
// shell:true would pass these args through a shell unescaped.
execFileSync(process.execPath, [join(root, "node_modules", "prisma", "build", "index.js"), "generate", "--schema", DERIVED], {
  cwd: root,
  stdio: "inherit",
});
console.log(
  "[dev-client] Done. prisma/schema.prisma is unchanged (still postgresql).\n" +
    "[dev-client] NOTE: a bare `npx prisma generate` or a fresh `npm install` will\n" +
    "[dev-client] overwrite this with a Postgres client — re-run this script if\n" +
    "[dev-client] `npm run dev:web` starts reporting a datasource protocol error.",
);
